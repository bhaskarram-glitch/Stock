-- infra/db/migrations/0005_live_candles.sql — storage for live streaming (Phase 3, 2026-10-18).
--
-- Up to ~10,600 instruments streamed in 1m/5m/15m/60m candles is millions of rows a day, so live
-- candles get their own compact tables instead of market_candles (uuid + text key per row):
--   live_candles_fine  1m and 5m   partitioned by IST day   — rolling retention (decided after the
--                                                             measuring day); excluded from nightly
--                                                             backups because Upstox can re-serve
--                                                             minute history
--   live_candles       15m and 60m partitioned by IST month — kept permanently, backed up
-- Rows point at instruments by a small integer id (`instruments.sid`) and always at the contract's
-- PERMANENT key row (`<segment>|<token>|<DD-MM-YYYY>`), never the trading key.
-- Partitions are created by ensure_live_partitions(day), which the worker (role stock_app, which
-- cannot run DDL) may call: it runs with the rights of the schema owner.

alter table instruments add column sid integer generated by default as identity;
alter table instruments add constraint instruments_sid_unique unique (sid);

create table live_candles_fine (
  sid          integer          not null,
  interval_min smallint         not null check (interval_min in (1, 5)),
  bucket_start timestamptz      not null,
  open         double precision not null,
  high         double precision not null,
  low          double precision not null,
  close        double precision not null,
  volume       bigint,
  oi           bigint,
  primary key (sid, interval_min, bucket_start)
) partition by range (bucket_start);

create table live_candles (
  sid          integer          not null,
  interval_min smallint         not null check (interval_min in (15, 60)),
  bucket_start timestamptz      not null,
  open         double precision not null,
  high         double precision not null,
  low          double precision not null,
  close        double precision not null,
  volume       bigint,
  oi           bigint,
  primary key (sid, interval_min, bucket_start)
) partition by range (bucket_start);

comment on table live_candles_fine is '1m/5m live candles, one partition per IST day (live_candles_fine_YYYYMMDD); rolling retention; not in nightly backups';
comment on table live_candles is '15m/60m live candles, one partition per IST month (live_candles_YYYYMM); kept permanently';

-- Idempotent: creates the day partition of live_candles_fine and the month partition of
-- live_candles that contain p_day (IST). Called by the streaming worker at start and on day change.
create function ensure_live_partitions(p_day date) returns void
language plpgsql security definer set search_path = public as $$
declare
  m date := date_trunc('month', p_day)::date;
begin
  execute format(
    'create table if not exists %I partition of live_candles_fine for values from (%L) to (%L)',
    'live_candles_fine_' || to_char(p_day, 'YYYYMMDD'),
    p_day::timestamp at time zone 'Asia/Kolkata',
    (p_day + 1)::timestamp at time zone 'Asia/Kolkata');
  execute format(
    'create table if not exists %I partition of live_candles for values from (%L) to (%L)',
    'live_candles_' || to_char(m, 'YYYYMM'),
    m::timestamp at time zone 'Asia/Kolkata',
    (m + interval '1 month')::timestamp at time zone 'Asia/Kolkata');
end $$;

revoke all on function ensure_live_partitions(date) from public;
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'stock_app') then
    grant execute on function ensure_live_partitions(date) to stock_app;
    grant select, insert, update, delete on live_candles_fine, live_candles to stock_app;
  end if;
end $$;
